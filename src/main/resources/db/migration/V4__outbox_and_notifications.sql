-- V4: the transactional outbox and the notification worker's record (Phase 3, step 1). Flyway runs it once on every
-- database that is still at V3.
--
-- 1. The outbox: events waiting to be sent to Kafka.
--    PaymentService inserts a row in the SAME transaction that confirms the hold and creates the order. Either both
--    commit or neither does, so an order never exists without its event, and an event never exists for an order that
--    rolled back. OutboxRelay later sends each PENDING row to Kafka and marks it SENT.
--
--    event_id is a random UUID made in Java, not the row id: ids start again at 1 after a test resets the tables (or
--    a restore), but a consumer remembers event ids forever to drop duplicates, so they must never repeat.
--    topic and message_key say where the relay sends it: the Kafka topic, and the key that picks the partition.
--    payload is the event as JSON text, exactly the bytes Kafka will carry.
--    attempts / next_attempt_at / last_error: when Kafka is down, the relay waits longer after each failed try.
CREATE TABLE outbox_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         UUID          NOT NULL,
    aggregate_type   VARCHAR(50)   NOT NULL,
    aggregate_id     BIGINT        NOT NULL,
    event_type       VARCHAR(50)   NOT NULL,
    topic            VARCHAR(100)  NOT NULL,
    message_key      VARCHAR(100)  NOT NULL,
    payload          TEXT          NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    attempts         INT           NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMPTZ   NOT NULL,
    last_error       VARCHAR(500),
    created_at       TIMESTAMPTZ   NOT NULL,
    sent_at          TIMESTAMPTZ,
    CONSTRAINT outbox_events_event_id_unique UNIQUE (event_id),
    CONSTRAINT outbox_events_status_valid CHECK (status IN ('PENDING', 'SENT'))
);

-- The relay asks "which PENDING rows are due?" every half second. A partial index holds only PENDING rows, so it
-- stays tiny even when millions of SENT rows pile up (the same idea as holds_due_for_expiry in V1).
CREATE INDEX outbox_events_due ON outbox_events (next_attempt_at, id) WHERE status = 'PENDING';

-- 2. Notifications the worker sent: one row per event, so a duplicate delivery from Kafka is recognised and skipped.
--    Kafka (with this outbox) delivers "at least once": the same event can arrive twice. The primary key on event_id
--    turns that into "the customer gets the message once".
CREATE TABLE notifications (
    event_id    UUID          PRIMARY KEY,
    user_id     VARCHAR(64)   NOT NULL,
    order_id    BIGINT        NOT NULL,
    message     VARCHAR(500)  NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL
);
