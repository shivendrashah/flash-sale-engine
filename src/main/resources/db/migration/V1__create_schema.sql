-- Products: things we sell (an iPhone, a MacBook). A product exists on its own, outside any sale.
CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200)   NOT NULL,
    regular_price  NUMERIC(12, 2) NOT NULL CHECK (regular_price >= 0),
    created_at     TIMESTAMPTZ    NOT NULL
);

-- Sales: a time window, e.g. "Diwali Flash Sale, 10:00 to 10:30".
CREATE TABLE sales (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    starts_at   TIMESTAMPTZ  NOT NULL,
    ends_at     TIMESTAMPTZ  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT sales_window_valid CHECK (ends_at > starts_at)
);

-- Sale items: one product inside one sale, with limited stock.
-- available_stock is the "hot" number that thousands of buyers fight over.
CREATE TABLE sale_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id          BIGINT         NOT NULL REFERENCES sales (id),
    product_id       BIGINT         NOT NULL REFERENCES products (id),
    sale_price       NUMERIC(12, 2) NOT NULL CHECK (sale_price >= 0),
    total_stock      INT            NOT NULL CHECK (total_stock >= 0),
    available_stock  INT            NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0,
    -- Last line of defence: whatever the code does, stock can never go below 0 or above what we started with.
    CONSTRAINT sale_items_stock_in_range CHECK (available_stock BETWEEN 0 AND total_stock),
    CONSTRAINT sale_items_one_per_product UNIQUE (sale_id, product_id)
);

-- Holds: a temporary reservation (10 minutes by default) that keeps stock aside while the user pays.
CREATE TABLE holds (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          VARCHAR(64)    NOT NULL,
    sale_id          BIGINT         NOT NULL REFERENCES sales (id),
    status           VARCHAR(20)    NOT NULL,
    total_amount     NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
    expires_at       TIMESTAMPTZ    NOT NULL,
    idempotency_key  VARCHAR(100)   NOT NULL,
    request_hash     VARCHAR(64)    NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL,
    updated_at       TIMESTAMPTZ    NOT NULL,
    CONSTRAINT holds_status_valid CHECK (status IN ('HELD', 'PAYMENT_PENDING', 'CONFIRMED', 'EXPIRED', 'CANCELLED')),
    -- The same user sending the same Idempotency-Key twice can never end up with two holds.
    CONSTRAINT holds_one_per_idempotency_key UNIQUE (user_id, idempotency_key)
);

-- The expiry job keeps asking "which HELD holds are past their time?".
-- A partial index only contains HELD rows, so it stays small and fast even with millions of finished holds.
CREATE INDEX holds_due_for_expiry ON holds (expires_at) WHERE status = 'HELD';

CREATE TABLE hold_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id       BIGINT         NOT NULL REFERENCES holds (id),
    sale_item_id  BIGINT         NOT NULL REFERENCES sale_items (id),
    quantity      INT            NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT hold_items_one_line_per_item UNIQUE (hold_id, sale_item_id)
);
CREATE INDEX hold_items_by_sale_item ON hold_items (sale_item_id);

-- Payments: one row per payment attempt for a hold.
CREATE TABLE payments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id          BIGINT         NOT NULL REFERENCES holds (id),
    user_id          VARCHAR(64)    NOT NULL,
    provider         VARCHAR(20)    NOT NULL,
    amount           NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    status           VARCHAR(20)    NOT NULL,
    provider_ref     VARCHAR(100),
    failure_reason   VARCHAR(200),
    idempotency_key  VARCHAR(100)   NOT NULL,
    request_hash     VARCHAR(64)    NOT NULL,
    -- Random key we send to the payment gateway. Random (not "payment-<id>") so it can never repeat,
    -- even after a database restore or when two environments share one gateway account.
    gateway_key      VARCHAR(64)    NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL,
    updated_at       TIMESTAMPTZ    NOT NULL,
    CONSTRAINT payments_gateway_key_unique UNIQUE (gateway_key),
    CONSTRAINT payments_status_valid CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT payments_one_per_idempotency_key UNIQUE (user_id, idempotency_key)
);
CREATE INDEX payments_by_hold ON payments (hold_id);
-- Even if the code had a bug, a hold could never have two payments in flight or two successful payments.
CREATE UNIQUE INDEX payments_one_pending_per_hold ON payments (hold_id) WHERE status = 'PENDING';
CREATE UNIQUE INDEX payments_one_success_per_hold ON payments (hold_id) WHERE status = 'SUCCEEDED';

-- Orders: the permanent record of a purchase, created when payment succeeds.
CREATE TABLE orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id       BIGINT         NOT NULL REFERENCES holds (id),
    payment_id    BIGINT         NOT NULL REFERENCES payments (id),
    user_id       VARCHAR(64)    NOT NULL,
    total_amount  NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
    status        VARCHAR(20)    NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL,
    CONSTRAINT orders_one_per_hold UNIQUE (hold_id)
);
